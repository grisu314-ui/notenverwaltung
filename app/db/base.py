"""Declarative base and constraint naming convention.

Every constraint gets a deterministic name. SQLite cannot alter or drop an
unnamed constraint; Alembic's batch mode rebuilds the table and needs the name
to reproduce it. Setting this up afterwards would require rewriting the whole
schema, so it belongs in the very first migration.
"""

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
